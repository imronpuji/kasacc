    public function ptkpAmount(?string $ptkp): int
    {
        if (! $ptkp || ! isset(self::PTKP[$ptkp])) {
            throw new DomainException('Status PTKP karyawan belum diisi atau tidak dikenal.');
        }

        return self::PTKP[$ptkp];
    }

    public function category(?string $ptkp): string
    {
        $this->ptkpAmount($ptkp);

        return match (true) {
            in_array($ptkp, ['TK/0', 'TK/1', 'K/0']) => 'A',
            $ptkp === 'K/3' => 'C',
            default => 'B',
        };
    }

    public function terBps(string $category, int $gross): int
    {
        foreach (self::TER[$category] as [$upper, $bps]) {
            if ($upper === null || $gross <= $upper) {
                return $bps;
            }
        }

        return 0;
    }

    /** Tarif progresif Pasal 17 atas penghasilan kena pajak (dibulatkan turun ke ribuan). */
    public function progressive(int $pkp): int
    {
        $pkp = intdiv(max($pkp, 0), 1000) * 1000;
        $tax = 0;
        $prev = 0;
        foreach ([[60_000_000, 500], [250_000_000, 1500], [500_000_000, 2500], [5_000_000_000, 3000], [PHP_INT_MAX, 3500]] as [$limit, $bps]) {
            if ($pkp <= $prev) {
                break;
            }
            $tax += PayrollSettings::pct(min($pkp, $limit) - $prev, $bps);
            $prev = $limit;
        }

        return $tax;
    }

    public function annualTax(int $annualGross, int $annualJhtJp, string $ptkp): int
    {
        $jobCost = min(PayrollSettings::pct($annualGross, PayrollSettings::get('job_cost_bps')), PayrollSettings::get('job_cost_cap'));
        $pkp = $annualGross - $jobCost - $annualJhtJp - $this->ptkpAmount($ptkp);

        return $this->progressive($pkp);
    }
